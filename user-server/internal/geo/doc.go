// Package geo 是 GEO（生成式引擎优化，Generative Engine Optimization）业务域的
// 架构说明与设计决策锚点。
//
// 本目录按五层架构组织：
//
//	controller → service → repository → model
//	dto         承载请求/响应契约
//
// ┌─────────────────────────────────────────────────────────────────────────┐
// │ 设计声明：单租户共享工作区（无多租户设计）                                │
// └─────────────────────────────────────────────────────────────────────────┘
//
// GEO 模块不做多租户隔离，这是有意的产品决策而非缺陷：
//
//   - 所有 GEO 资源（关键词、文章、优化记录、验证结果、知识库文档、工作流、
//     平台账号、发布记录）均为品牌级共享资源，全体登录用户可见可操作；
//   - 数据模型不包含 user_id / tenant_id 等归属字段，仓储层不做归属过滤；
//   - 唯一的权限分级：GEO 全局配置的写入与优化（PUT /geo/config、
//     POST /geo/config/optimize）仅管理员可操作（见 router/geo_routes.go），
//     防止普通成员误改品牌配置导致全链路 GEO 内容偏移。
//
// 若未来产品升级为多租户，需同步改造：model 归属字段与索引、repository 查询
// 作用域、service 身份透传、controller 认证上下文提取，以及存量数据迁移，
// 属于跨层专项，不接受局部打补丁。
//
// ┌─────────────────────────────────────────────────────────────────────────┐
// │ 其他设计决策                                                             │
// └─────────────────────────────────────────────────────────────────────────┘
//
//   - 平台账号凭据：落库经 AES-256-GCM 加密（internal/pkg/crypto，
//     FIELD_ENCRYPTION_KEY ≥32 字节）；未配置密钥时降级明文存储并记录告警，
//     保证业务连续性；接口层一律脱敏（dto.PlatformAccountResponse），
//     任何端点不得回显明文凭据。
//   - LLM 成本记账：token 用量来自 Dispatcher 真实 Usage；金额按内置
//     定价表估算（EstimateCostUSD 返回 USD/CNY 双值），为估算值而非账单值。
//   - 已知演进方向（数据量增长后启动，当前不做）：知识库 pgvector 语义检索、
//     workflow JSON 字段 JSONB 化、geo_api_calls 时间索引。
package geo
